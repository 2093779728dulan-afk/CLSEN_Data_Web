test("catalog read failure recovers on request; forbidden reads have no retry action", async ({ page }, testInfo) => {
  const { requests, recover } = await fixture(page, "failure");
  await expect(page.getByRole("alert")).toContainText("商品主档读取未完成");
  const initialReads = requests.filter(request => request.path === "/api/catalog/styles").length;
  expect(initialReads).toBeGreaterThan(0);
  await testInfo.attach("initial-catalog-reads", { body: JSON.stringify({ initialReads }), contentType: "application/json" });
  recover();
  await page.getByRole("button", { name: "重新读取", exact: true }).click();
  await expect(page.getByRole("searchbox", { name: "查找商品" })).toBeVisible();
  expect(requests.filter(request => request.path === "/api/catalog/styles").length).toBeGreaterThan(initialReads);
  expect(requests.filter(request => request.method !== "GET")).toEqual([]);
  await page.goto("about:blank");
  await page.unrouteAll({ behavior: "wait" });
  const { requests: forbidden } = await fixture(page, "forbidden");
  await expect(page.getByRole("alert")).toContainText("没有查看此商品主档页面的权限");
  await expect(page.getByRole("button", { name: "刷新商品主档", exact: true })).toBeDisabled();
  await expect(page.getByRole("button", { name: "重新读取", exact: true })).toHaveCount(0);
  expect(forbidden.filter(request => request.path === "/api/catalog/styles").length).toBeGreaterThan(0);
});

test("catalog separates uninitialized, approved-empty and viewer states", async ({ page }) => {
  await fixture(page, "uninitialized");
  await expect(page.getByRole("heading", { name: "商品主档尚未初始化" })).toBeVisible();
  await expect(page.getByRole("link", { name: "开始初始化商品主档" })).toBeVisible();
  await page.goto("about:blank");
  await page.unrouteAll({ behavior: "wait" });
  await fixture(page, "empty");
  await expect(page.getByRole("heading", { name: "当前主档尚无商品" })).toBeVisible();
  await expect(page.getByRole("heading", { name: "商品主档尚未初始化" })).toHaveCount(0);
  await page.goto("about:blank");
  await page.unrouteAll({ behavior: "wait" });
  const { requests } = await fixture(page, "viewer");
  await expect(page.getByRole("searchbox", { name: "查找商品" })).toBeVisible();
  await expect(page.getByRole("navigation", { name: "商品主档导航" }).getByRole("link")).toHaveCount(1);
  await expect(page.getByRole("link", { name: "进入批量维护" })).toHaveCount(0);
  await expect(page.getByRole("region", { name: "商品主档列表" }).getByText("只读", { exact: true })).toBeVisible();
  expect(requests.filter(request => request.method !== "GET")).toEqual([]);
});

