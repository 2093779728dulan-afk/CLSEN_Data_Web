import { expect, test, type Page } from "@playwright/test";

async function fixture(page: Page, mode: "normal" | "failure" | "uninitialized" | "empty" | "viewer" | "forbidden" = "normal") {
  const requests: Array<{ path: string; method: string }> = [];
  let failed = mode === "failure";
  let listStatus = 0;
  let detailStatus = 0;
  let listDelay = 80;
  const styles = Array.from({ length: 26 }, (_, i) => ({ style_id: 700 + i, style_code: `DEMO-${String(i + 1).padStart(2, "0")}`, standard_name: i < 2 ? "同名示例商品" : i === 2 ? "很长的示例商品名称用于检查手机窄屏换行与身份阅读".repeat(3) : `示例商品 ${i + 1}`, category_name: "示例分类", category_id: 1, category_code: "DEMO", category_recorded: true, revision: 1, status: i === 25 ? "paused" : i % 4 === 0 ? "disabled" : i % 4 === 1 ? "active" : "enabled", variant_count: 2, seller_sku_count: 3, source_summary: { first_seen_date: "2026-07-01", latest_seen_date: "2026-09-30", source_report_count: 3, observation_count: 14 } }));
  await page.route(/^https?:\/\/[^/]+\/api\//, async route => {
    const path = new URL(route.request().url()).pathname;
    requests.push({ path, method: route.request().method() });
    if (path === "/api/auth/me") return route.fulfill({ json: { id: 77, username: "synthetic-catalog-reader", display_name: "示例目录账号", roles: [mode === "viewer" ? "viewer" : "data_manager"] } });
    if (path === "/api/data-calendar/site-context") return route.fulfill({ json: { site_id: 1, site_code: "US", display_name: "示例站点", site_config_version_id: 2, source_timezone: "UTC", reporting_timezone: "UTC", currency_code: "USD" } });
    if (path === "/api/dashboard/style-readiness") return route.fulfill({ json: { prerequisites_present: false, catalog_approved: mode !== "uninitialized", published_reports: 0 } });
    if (path === "/api/catalog/source-scope") return route.fulfill({ json: { status: "unconfirmed", permissions: { can_confirm: false }, site_config_revision: 1 } });
    if (path === "/api/catalog/versions") return route.fulfill({ json: { versions: [] } });
    if (path === "/api/catalog/styles") {
      if (listStatus) return route.fulfill({ status: listStatus, json: { error: { code: "UNAVAILABLE" } } });
      if (mode === "forbidden") return route.fulfill({ status: 403, json: { error: { code: "FORBIDDEN", message: "没有权限。" } } });
      if (failed) return route.fulfill({ status: 503, json: { error: { code: "UNAVAILABLE", message: "示例读取失败。" } } });
      await new Promise(resolve => setTimeout(resolve, listDelay));
      return route.fulfill({ json: { catalog: mode === "uninitialized" ? null : { catalog_publication_revision: 4, catalog_version_id: 3, version_number: 3, skus: [], styles: mode === "empty" ? [] : styles } } });
    }
    const match = path.match(/^\/api\/catalog\/styles\/(\d+)$/);
    if (match && detailStatus) return route.fulfill({ status: detailStatus, json: { error: { code: "UNAVAILABLE" } } });
    if (match) return route.fulfill({ json: { style: styles.find(item => item.style_id === Number(match[1])), skus: [], catalog_version_id: 3, permissions: { can_edit: false, can_manage_categories: false } } });
    if (path.endsWith("/pending-items")) return route.fulfill({ json: { items: [], permissions: { can_review: false } } });
    return route.fulfill({ json: {} });
  });
  await page.goto("/catalog");
  return { requests, recover: () => { failed = false; }, listMode: (status: number, delay = 80) => { listStatus = status; listDelay = delay; }, detailMode: (status: number) => { detailStatus = status; } };
}

